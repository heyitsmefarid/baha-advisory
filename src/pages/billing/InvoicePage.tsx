import React from "react";
import { useParams } from "react-router-dom";
import { doc } from "firebase/firestore";
import { Callout, Spinner, formatDateTime } from "../../components/ui";
import { useFirestoreDoc } from "../../hooks/useFirestoreDoc";
import { db } from "../../firebase";
import { formatPhp } from "../../../shared/plans";
import type { BillingInvoice } from "../../../shared/types";

/** Printable receipt (readable by the org's admins and the Super Admin). */
export default function InvoicePage() {
  const { id = "" } = useParams();
  const { data: inv, loading, error } = useFirestoreDoc<Omit<BillingInvoice, "id">>(() => doc(db, "billing_invoices", id), [id]);
  if (loading) return <div className="page-fallback"><Spinner /></div>;
  if (error || !inv) return <div className="invoice"><Callout tone="danger">Receipt not found or not accessible.</Callout></div>;
  return (
    <div className="invoice">
      <header className="invoice__head">
        <img src="/logo/bahadvisory_logo.png" alt="Bahadvisory" className="invoice__logo" />
        <div>
          <h1>Official receipt{inv.isDemo ? " — SANDBOX" : ""}</h1>
          <p className="mono">{inv.number}</p>
        </div>
      </header>
      {inv.isDemo && <p className="invoice__sandbox">Sandbox transaction — no money was received. Not valid as a tax document.</p>}
      <dl className="kv">
        <div><dt>Billed to</dt><dd>{inv.orgName}</dd></div>
        <div><dt>Date</dt><dd>{formatDateTime(inv.issuedAt)}</dd></div>
        <div><dt>Payment via</dt><dd>{inv.provider}</dd></div>
        <div><dt>Status</dt><dd>{inv.status}</dd></div>
      </dl>
      <table className="data-table">
        <thead><tr><th>Description</th><th className="num">Amount</th></tr></thead>
        <tbody>
          {inv.lines.map((l, i) => (<tr key={i}><td>{l.description}</td><td className="num">{formatPhp(l.amountPhp)}</td></tr>))}
          <tr><td><strong>Total</strong></td><td className="num"><strong>{formatPhp(inv.totalPhp)}</strong></td></tr>
        </tbody>
      </table>
      <p className="tiny">Generated by Bahadvisory. For BIR-registered official receipts, configure your accounting system's integration.</p>
      <button className="no-print" onClick={() => window.print()}>Print</button>
    </div>
  );
}
